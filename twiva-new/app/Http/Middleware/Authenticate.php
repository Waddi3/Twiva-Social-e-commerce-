<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Auth\Middleware\Authenticate as Middleware;
use Illuminate\Http\Request;
use Illuminate\Support\Str;

class Authenticate extends Middleware {
    public ?string $guard = null;

    public function handle($request, Closure $next, ...$guards)
    {
        $this->guard = $guards[0] ?? null;
        return parent::handle($request, $next, $guards[0] ?? []); // TODO: Change the autogenerated stub
    }

    /**
     * Get the path the user should be redirected to when they are not authenticated.
     *
     * @param Request $request
     * @return string|null
     */
    protected function redirectTo($request)
    {
        if (!$request->expectsJson())
        {
            if (Str::contains($request->getHost(), 'admin'))
            {
                return route('admin.login');
            }
            if ($this->guard == 'buyer' && request()->has('account'))
            {
                return route('buyer.login', ['account' => request('account')]);
            }
            else if ($this->guard == 'buyer')
            {
                return route('ecommerce.login');
            }
            return route('ecommerce.index');

        }

    }
}
