<?php

namespace Modules\Shop\Http\Requests\ShopSite;

use Illuminate\Contracts\Validation\Validator;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class PayRequest extends FormRequest {


    public function rules(): array
    {
        if (checkIfCouponFullyCoversOrder())
        {
            return [];
        }
        return [
            'payment_type'                => ['required', 'in:1,2,3,4,5,6,8'],
            'phone_number'                => [Rule::requiredIf($this->payment_type == 1)],
            'spotit_bank'                 => [Rule::requiredIf($this->payment_type == 6)],
            'spotit_phone_number'         => [Rule::requiredIf($this->payment_type == 6)],
            'is_group_paying'             => ['nullable', 'string'],
            'amount_payment_group_buying' => ['nullable', 'numeric','min:1', Rule::requiredIf(in_array(request('is_group_paying') , ['on','1']))],
            'pesapal_phone_number' => [Rule::requiredIf($this->payment_type == 8)],
        ];
    }

    protected function failedValidation(Validator $validator)
    {
        parent::failedValidation($validator); // TODO: Change the autogenerated stub
    }

    public function authorize(): bool
    {
        return true;
    }
}
